function updateLangFile($filePath, $newKeys) {
    $existing = include $filePath;
    foreach ($newKeys as $k => $v) {
        $existing[$k] = $v;
    }
    $content = "<?php\n\nreturn " . var_export($existing, true) . ";\n";
    file_put_contents($filePath, $content);
}

